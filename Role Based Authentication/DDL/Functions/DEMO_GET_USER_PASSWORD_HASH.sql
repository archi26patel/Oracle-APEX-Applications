create or replace FUNCTION DEMO_GET_USER_PASSWORD_HASH (
    P_USERNAME IN VARCHAR2,
    P_PASSWORD IN VARCHAR2
) RETURN VARCHAR2 
IS
    V_HASH VARCHAR2(4000);
BEGIN
    IF P_USERNAME IS NULL OR P_PASSWORD IS NULL THEN
        RETURN NULL;
    END IF;
    
    V_HASH := APEX_UTIL.GET_HASH(APEX_T_VARCHAR2(UPPER(TRIM(P_USERNAME)), P_PASSWORD), NULL);
    RETURN V_HASH;
EXCEPTION
    WHEN OTHERS THEN
        RETURN NULL;
END DEMO_GET_USER_PASSWORD_HASH;
/