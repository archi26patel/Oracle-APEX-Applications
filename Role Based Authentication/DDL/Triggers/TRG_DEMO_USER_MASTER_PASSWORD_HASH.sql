create or replace TRIGGER TRG_DEMO_USER_MASTER_PASSWORD_HASH 
BEFORE INSERT OR UPDATE OF PASSWORD, EMAIL ON DEMO_USER_MASTER 
FOR EACH ROW 
BEGIN 
    IF :NEW.PASSWORD IS NOT NULL THEN
        IF INSERTING OR (:NEW.PASSWORD != NVL(:OLD.PASSWORD, 'EMPTY_HASH_KEY')) THEN
            :NEW.PASSWORD := DEMO_GET_USER_PASSWORD_HASH(:NEW.EMAIL, :NEW.PASSWORD); 
        END IF;
    END IF;
END TRG_DEMO_USER_MASTER_PASSWORD_HASH;
/