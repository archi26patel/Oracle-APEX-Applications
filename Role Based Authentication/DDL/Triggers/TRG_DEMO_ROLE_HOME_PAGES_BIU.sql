create or replace TRIGGER TRG_DEMO_ROLE_HOME_PAGES_BIU
BEFORE INSERT OR UPDATE ON DEMO_ROLE_HOME_PAGES
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.CREATED_AT := GET_IST_SYSTIMESTAMP;
        :NEW.CREATED_BY := COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
    END IF;
    :NEW.UPDATED_AT := GET_IST_SYSTIMESTAMP;
    :NEW.UPDATED_BY := COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
END TRG_DEMO_ROLE_HOME_PAGES_BIU;
/