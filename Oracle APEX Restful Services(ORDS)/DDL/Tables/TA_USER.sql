  CREATE TABLE "TA_USER" 
   (	"USER_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"USERNAME" VARCHAR2(255 CHAR), 
	"PASSWORD" VARCHAR2(255 CHAR), 
	"CREATED" TIMESTAMP (6), 
	"CREATED_BY" VARCHAR2(255 CHAR), 
	"UPDATED" TIMESTAMP (6), 
	"UPDATED_BY" VARCHAR2(255 CHAR), 
	 CONSTRAINT "TA_USER_PK" PRIMARY KEY ("USER_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "TA_USER_CON_USERNAME_UQ" UNIQUE ("USERNAME")
  USING INDEX  ENABLE
   ) ;

  CREATE OR REPLACE EDITIONABLE TRIGGER "TA_USER_BIU" 
BEFORE INSERT OR UPDATE ON TA_USER
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.CREATED := SYSDATE;
        :NEW.CREATED_BY := NVL(V('APP_USER'), USER);
    END IF;

        :NEW.UPDATED := SYSDATE;
        :NEW.UPDATED_BY := NVL(V('APP_USER'), USER);
END;
/
ALTER TRIGGER "TA_USER_BIU" ENABLE;