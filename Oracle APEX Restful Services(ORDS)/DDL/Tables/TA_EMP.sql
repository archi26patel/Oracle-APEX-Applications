  CREATE TABLE "TA_EMP" 
   (	"ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"FIRST_NAME" VARCHAR2(100), 
	"LAST_NAME" VARCHAR2(100), 
	"EMAIL_ID" VARCHAR2(150), 
	"PASSWORD_TXT" VARCHAR2(100), 
	"AGE" NUMBER, 
	"COMPLETION_PCT" NUMBER, 
	"BIRTH_DATE" DATE, 
	"GENDER" VARCHAR2(10), 
	"CITY" VARCHAR2(50), 
	"COUNTRY" VARCHAR2(50), 
	"TERMS_ACCEPTED" VARCHAR2(1), 
	"SKILLS" VARCHAR2(200), 
	"ADDRESS" CLOB, 
	"ACTIVE_FLAG" VARCHAR2(1), 
	"PROFILE_PHOTO" BLOB, 
	"PHOTO_MIME" VARCHAR2(100), 
	"DOCUMENT_FILE" BLOB, 
	"DOC_MIME" VARCHAR2(100), 
	"CREATED_ON" DATE DEFAULT SYSDATE, 
	"CREATED_BY" VARCHAR2(100), 
	"UPDATED_ON" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"PHOTO_FILE_NAME" VARCHAR2(255), 
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE
   ) ;

  CREATE OR REPLACE EDITIONABLE TRIGGER "TA_EMP_BIU" 
BEFORE INSERT OR UPDATE ON TA_EMP
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.CREATED_ON := SYSDATE;
        :NEW.CREATED_BY := NVL(V('APP_USER'), USER);
    END IF;

    IF UPDATING THEN
        :NEW.UPDATED_ON := SYSDATE;
        :NEW.UPDATED_BY := NVL(V('APP_USER'), USER);
    END IF;
END;
/
ALTER TRIGGER "TA_EMP_BIU" ENABLE;